class I18nManager {
  constructor() {
    this.storageKey = 'sudoku_arena_lang';
    this.currentLang = this.detectLanguage();
  }

  detectLanguage() {
    const saved = localStorage.getItem(this.storageKey);
    if (saved && I18N_LANGUAGES[saved]) return saved;

    const navLang = (navigator.language || 'es').split('-')[0].toLowerCase();
    if (I18N_LANGUAGES[navLang]) return navLang;

    return 'es';
  }

  setLanguage(lang) {
    if (!I18N_LANGUAGES[lang]) return;
    this.currentLang = lang;
    try {
      localStorage.setItem(this.storageKey, lang);
    } catch (e) {}

    this.applyTranslations();

    if (window.sudokuApp && typeof window.sudokuApp.onLanguageChanged === 'function') {
      window.sudokuApp.onLanguageChanged(lang);
    }
  }

  t(key, params = {}) {
    const dict = I18N_TRANSLATIONS[this.currentLang] || I18N_TRANSLATIONS.es;
    const langDict = (typeof I18N_LANGUAGES !== 'undefined' && I18N_LANGUAGES[this.currentLang]) ? I18N_LANGUAGES[this.currentLang] : {};
    let text = dict[key] || langDict[key] || I18N_TRANSLATIONS.es[key] || (typeof I18N_LANGUAGES !== 'undefined' && I18N_LANGUAGES.es ? I18N_LANGUAGES.es[key] : null) || key;

    for (const [pKey, pVal] of Object.entries(params)) {
      text = text.split('{' + pKey + '}').join(pVal);
    }
    return text;
  }

  applyTranslations() {
    // 1. Textos data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translation = this.t(key);
      if (translation && translation !== key) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = translation;
        } else {
          el.textContent = translation;
        }
      }
    });

    // 2. Títulos/Tooltips data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const translation = this.t(key);
      if (translation && translation !== key) {
        el.title = translation;
      }
    });

    // 3. Actualizar etiqueta visible del selector en cabecera
    const langBtnText = document.getElementById('current-lang-code');
    if (langBtnText && I18N_LANGUAGES[this.currentLang]) {
      langBtnText.textContent = I18N_LANGUAGES[this.currentLang].name;
    }

    // 4. Actualizar estado activo en modal de idioma
    document.querySelectorAll('.lang-card').forEach(card => {
      card.classList.toggle('active', card.dataset.lang === this.currentLang);
    });

    // 5. Atributo lang en <html>
    document.documentElement.lang = this.currentLang;

    // 6. Actualizar enlaces a Top-Sudoku con el idioma actual
    try {
      const isLocal = typeof window !== 'undefined' && (window.location.hostname === 'localhost' || window.location.hostname === '127.0.0.1');
      const baseUrl = isLocal ? '/top-sudoku/' : 'https://guitusol.github.io/top-sudoku/';
      const targetUrl = `${baseUrl}?lang=${this.currentLang}`;
      document.querySelectorAll('.link-to-top-sudoku').forEach(el => {
        el.href = targetUrl;
      });
    } catch (e) {
      // Ignorar en entornos sin DOM completo
    }
  }
}

window.i18n = new I18nManager();
